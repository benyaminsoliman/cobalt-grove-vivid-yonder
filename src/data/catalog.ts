export function getProvider(id: string): Provider | undefined {
  return PROVIDERS.find((provider) => provider.id === id);
}

export function providerEndpoint(provider: Provider, region: string | undefined): string {
  if (provider.regions && provider.regions.length > 0) {
    const picked = provider.regions.find((item) => item.id === region) ?? provider.regions.find((item) => item.id === provider.defaultRegion) ?? provider.regions[0];
    return picked.endpoint;
  }
  if (!provider.endpoint) throw new Error(`${provider.name} has no endpoint.`);
  return provider.endpoint;
}

